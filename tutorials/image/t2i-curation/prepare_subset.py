"""Freeze a shard-level subset for the image curation workflow."""

import argparse
import json
from pathlib import Path

from nemo_curator.stages.image.io.subset import prepare_subset

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    prepare_subset(json.loads(args.config.read_text(encoding="utf-8")), args.output)
